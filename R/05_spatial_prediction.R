# 14. MODAL CATEGORICAL VALUES
# ============================================================

get_modal_level <- function(x) {
  
  x <- as.character(x)
  
  x <- x[!is.na(x)]
  
  if (!length(x)) {
    
    stop(
      "No non-missing values available for categorical variable."
    )
  }
  
  tab <- sort(
    table(x),
    decreasing = TRUE
  )
  
  names(tab)[1]
}

