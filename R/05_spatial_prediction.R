# ============================================================
# 05_spatial_prediction.R
# NATIONAL 1-KM VECTOR ABUNDANCE PREDICTION - UGANDA
# ============================================================

# PURPOSE
# Predict national Anopheles gambiae s.l. abundance at 1-km
# resolution using the three fitted negative-binomial models.
#
# MODELS
# M1 = Household + season + travel +
#      sampling intensity + temporal trend
#
# M2 = M1 + environmental variables +
#      site random effect
#
# M3 = M2 + continental An. gambiae ecological offset
#
# PREDICTION TARGET
# Anopheles gambiae s.l. abundance
#
# PREDICTION PERIOD
# July
#
# M3 OFFSET
# Band 4 = An. gambiae continental prediction surface.
#
# NATIONAL PREDICTIONS
# Population-level predictions are generated by excluding
# site-specific random effects.
# ============================================================


