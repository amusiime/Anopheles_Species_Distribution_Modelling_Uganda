# 18. PREDICTION FUNCTION
# ============================================================

predict_model <- function(
    model,
    newdata) {
  
  newdata <- as.data.frame(
    newdata
  )
  
  # ----------------------------------------------------------
  # Month
  # ----------------------------------------------------------
  
  if ("month" %in% names(newdata)) {
    
    month_values <- as.integer(
      round(
        as.numeric(
          newdata$month
        )
      )
    )
    
    month_values[
      month_values < 1 |
        month_values > length(month_levels)
    ] <- NA_integer_
    
    newdata$month <- factor(
      month_levels[month_values],
      levels = month_levels,
      ordered = TRUE
    )
  }
  
  # ----------------------------------------------------------
  # Sprayed
  # ----------------------------------------------------------
  
  if ("sprayed" %in% names(newdata)) {
    
    sprayed_values <- as.integer(
      round(
        as.numeric(
          newdata$sprayed
        )
      )
    )
    
    sprayed_values[
      sprayed_values < 1 |
        sprayed_values > length(sprayed_levels)
    ] <- NA_integer_
    
    newdata$sprayed <- factor(
      sprayed_levels[sprayed_values],
      levels = sprayed_levels
    )
  }
  
  # ----------------------------------------------------------
  # House type
  # ----------------------------------------------------------
  
  if ("house_type" %in% names(newdata)) {
    
    house_type_values <- as.integer(
      round(
        as.numeric(
          newdata$house_type
        )
      )
    )
    
    house_type_values[
      house_type_values < 1 |
        house_type_values > length(house_type_levels)
    ] <- NA_integer_
    
    newdata$house_type <- factor(
      house_type_levels[house_type_values],
      levels = house_type_levels
    )
  }
  
  # ----------------------------------------------------------
  # Continental offset
  # ----------------------------------------------------------
  
  if ("log_continental_offset" %in% names(newdata)) {
    
    newdata$log_continental_offset <-
      as.numeric(
        newdata$log_continental_offset
      )
  }
  
  # ----------------------------------------------------------
  # Population-level prediction
  # ----------------------------------------------------------
  
  predict(
    model,
    newdata = newdata,
    type = "response",
    re.form = NA
  )
}


