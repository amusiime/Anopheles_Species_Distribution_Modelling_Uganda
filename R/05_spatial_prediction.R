# ============================================================
# 24. RUN NATIONAL SPATIAL PREDICTION
# ============================================================

run_prediction <- function(
    model,
    raster_stack,
    model_name) {
  
  output_file <- file.path(
    "outputs/predictions",
    paste0(
      "an_gambiae_",
      model_name,
      "_1km.tif"
    )
  )
  
  cat(
    "\nRunning spatial prediction: ",
    model_name,
    "\n",
    sep = ""
  )
  
  prediction <- terra::predict(
    raster_stack,
    model,
    fun = function(
    model,
    data) {
      
      predict_model(
        model,
        data
      )
    },
    na.rm = FALSE,
    filename = output_file,
    overwrite = TRUE
  )
  
  names(prediction) <-
    paste0(
      "an_gambiae_",
      model_name
    )
  
  cat(
    "Saved: ",
    output_file,
    "\n",
    sep = ""
  )
  
  prediction
}


