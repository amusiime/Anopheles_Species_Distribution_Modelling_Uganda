# 12. MODEL FACTOR LEVELS
# ============================================================

get_model_levels <- function(
    model,
    variable,
    data) {
  
  lev <- model$xlevels[[variable]]
  
  if (is.null(lev)) {
    
    lev <- levels(
      factor(
        data[[variable]]
      )
    )
  }
  
  lev
}

