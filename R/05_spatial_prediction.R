# 9. CONSTANT RASTER FUNCTION
# ============================================================

make_constant_raster <- function(
    template,
    value,
    name) {
  
  r <- terra::rast(
    template
  )
  
  r[] <- value
  
  names(r) <- name
  
  r
}


